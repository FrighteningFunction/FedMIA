#!/usr/bin/env bash
set -euo pipefail

# Final BINN/FedMIA patient-level evaluation.
#
# This launcher keeps the configuration aligned with the representative
# paper-style BINN setting we selected, but repeats it across multiple seeds and
# writes patient-level metrics through experiments/fedmia_binn_paper_grid.py.
#
# Default serious run:
#   GPU=0 bash membership_attack_binn_patient_eval.sh
#
# Plumbing check:
#   PLUMBING=1 bash membership_attack_binn_patient_eval.sh

export CUDA_VISIBLE_DEVICES="${GPU:-0}"

if [[ "${PLUMBING:-0}" == "1" ]]; then
  RUNS="${RUNS:-2}"
  CLIENT_GRID="${CLIENT_GRID:-5}"
  ROUND_GRID="${ROUND_GRID:-1}"
  LOCAL_EPOCH_GRID="${LOCAL_EPOCH_GRID:-1}"
  BETA_GRID="${BETA_GRID:-1}"
  SAMPLE_FRACTION_GRID="${SAMPLE_FRACTION_GRID:-1.0}"
  SAMPLES_PER_CLIENT_GRID="${SAMPLES_PER_CLIENT_GRID:-8}"
  CANDIDATE_COUNT="${CANDIDATE_COUNT:-4}"
  BATCH_SIZE="${BATCH_SIZE:-4}"
  DEVICE="${DEVICE:-cpu}"
  MAX_SAMPLES="${MAX_SAMPLES:-80}"
  FEATURE_LIMIT="${FEATURE_LIMIT:-256}"
else
  RUNS="${RUNS:-5}"
  CLIENT_GRID="${CLIENT_GRID:-10}"
  ROUND_GRID="${ROUND_GRID:-100}"
  LOCAL_EPOCH_GRID="${LOCAL_EPOCH_GRID:-2}"
  BETA_GRID="${BETA_GRID:-1}"
  SAMPLE_FRACTION_GRID="${SAMPLE_FRACTION_GRID:-1.0}"
  SAMPLES_PER_CLIENT_GRID="${SAMPLES_PER_CLIENT_GRID:-auto}"
  CANDIDATE_COUNT="${CANDIDATE_COUNT:-0}"
  BATCH_SIZE="${BATCH_SIZE:-16}"
  DEVICE="${DEVICE:-cuda}"
  MAX_SAMPLES="${MAX_SAMPLES:-0}"
  FEATURE_LIMIT="${FEATURE_LIMIT:-0}"
fi

GPU="${GPU:-0}"
LR="${LR:-0.03}"
WEIGHT_DECAY="${WEIGHT_DECAY:-5e-4}"
MOMENTUM="${MOMENTUM:-0.9}"
THRESHOLD="${THRESHOLD:-0.5}"
THRESHOLD_GRID="${THRESHOLD_GRID:-0.001,0.005,0.01,0.02,0.05,0.10,0.20,0.30,0.40,0.50,0.55,0.60,0.65,0.70,0.75,0.80,0.85,0.90}"
HOLDOUT_FRACTION="${HOLDOUT_FRACTION:-0.1}"
SEED="${SEED:-20260509}"
LOG_DIR="${LOG_DIR:-logs}"
REPORT_DIR="${REPORT_DIR:-reports}"
LOG_LEVEL="${LOG_LEVEL:-INFO}"

echo "=== BINN FedMIA patient-level evaluation ==="
echo "  RUNS=${RUNS}"
echo "  CLIENT_GRID=${CLIENT_GRID}"
echo "  ROUND_GRID=${ROUND_GRID}"
echo "  LOCAL_EPOCH_GRID=${LOCAL_EPOCH_GRID}"
echo "  BETA_GRID=${BETA_GRID}"
echo "  SAMPLE_FRACTION_GRID=${SAMPLE_FRACTION_GRID}"
echo "  SAMPLES_PER_CLIENT_GRID=${SAMPLES_PER_CLIENT_GRID}"
echo "  CANDIDATE_COUNT=${CANDIDATE_COUNT}"
echo "  HOLDOUT_FRACTION=${HOLDOUT_FRACTION}"
echo "  THRESHOLD=${THRESHOLD}"
echo "  DEVICE=${DEVICE}"
echo "  GPU=${GPU}"

RUNS="${RUNS}" \
CLIENT_GRID="${CLIENT_GRID}" \
ROUND_GRID="${ROUND_GRID}" \
LOCAL_EPOCH_GRID="${LOCAL_EPOCH_GRID}" \
BETA_GRID="${BETA_GRID}" \
SAMPLE_FRACTION_GRID="${SAMPLE_FRACTION_GRID}" \
SAMPLES_PER_CLIENT_GRID="${SAMPLES_PER_CLIENT_GRID}" \
CANDIDATE_COUNT="${CANDIDATE_COUNT}" \
BATCH_SIZE="${BATCH_SIZE}" \
LR="${LR}" \
WEIGHT_DECAY="${WEIGHT_DECAY}" \
MOMENTUM="${MOMENTUM}" \
THRESHOLD="${THRESHOLD}" \
THRESHOLD_GRID="${THRESHOLD_GRID}" \
HOLDOUT_FRACTION="${HOLDOUT_FRACTION}" \
SEED="${SEED}" \
DEVICE="${DEVICE}" \
GPU="${GPU}" \
MAX_SAMPLES="${MAX_SAMPLES}" \
FEATURE_LIMIT="${FEATURE_LIMIT}" \
LOG_DIR="${LOG_DIR}" \
REPORT_DIR="${REPORT_DIR}" \
LOG_LEVEL="${LOG_LEVEL}" \
bash membership_attack.sh
